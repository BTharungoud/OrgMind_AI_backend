CREATE EXTENSION IF NOT EXISTS vector;
CREATE SCHEMA IF NOT EXISTS orgmind;

CREATE TABLE IF NOT EXISTS orgmind.organization (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(150) NOT NULL,
  description text,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT organization_name_unique UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS orgmind.department (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES orgmind.organization(id),
  name varchar(150) NOT NULL,
  description text,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT department_org_name_unique UNIQUE (organization_id, name)
);

CREATE TABLE IF NOT EXISTS orgmind.role (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES orgmind.organization(id),
  department_id bigint REFERENCES orgmind.department(id),
  name varchar(150) NOT NULL,
  description text,
  is_admin boolean NOT NULL DEFAULT false,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT role_org_name_unique UNIQUE (organization_id, name)
);

CREATE TABLE IF NOT EXISTS orgmind.app_user (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES orgmind.organization(id),
  department_id bigint REFERENCES orgmind.department(id),
  role_id bigint NOT NULL REFERENCES orgmind.role(id),
  username varchar(100) NOT NULL,
  email varchar(320) NOT NULL,
  password_hash text NOT NULL,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT user_username_unique UNIQUE (username),
  CONSTRAINT user_email_unique UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS orgmind.refresh_token (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES orgmind.app_user(id) ON DELETE CASCADE,
  token_hash char(64) NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS orgmind.registration_token (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES orgmind.organization(id),
  token_hash char(64) NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS orgmind.user_settings (
  user_id bigint PRIMARY KEY REFERENCES orgmind.app_user(id) ON DELETE CASCADE,
  dark_mode boolean NOT NULL DEFAULT true,
  sidebar_position varchar(5) NOT NULL DEFAULT 'left',
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT sidebar_position_valid CHECK (sidebar_position IN ('left', 'right'))
);

CREATE TABLE IF NOT EXISTS orgmind.ingestion_request (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES orgmind.organization(id),
  department_id bigint REFERENCES orgmind.department(id),
  requested_by bigint NOT NULL REFERENCES orgmind.app_user(id),
  reviewed_by bigint REFERENCES orgmind.app_user(id),
  file_name text NOT NULL,
  mime_type varchar(150) NOT NULL,
  file_content bytea NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'PENDING',
  review_comment text,
  created_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz,
  CONSTRAINT ingestion_status_valid CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'FAILED'))
);

CREATE TABLE IF NOT EXISTS orgmind.document (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES orgmind.organization(id),
  department_id bigint REFERENCES orgmind.department(id),
  uploaded_by bigint NOT NULL REFERENCES orgmind.app_user(id),
  title text NOT NULL,
  source_url text,
  mime_type varchar(150) NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'PROCESSING',
  embedding_model varchar(150) NOT NULL,
  embedding_dimensions integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT document_status_valid CHECK (status IN ('PROCESSING', 'INDEXED', 'FAILED')),
  CONSTRAINT embedding_dimensions_positive CHECK (embedding_dimensions > 0)
);

CREATE TABLE IF NOT EXISTS orgmind.document_chunk (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id bigint NOT NULL REFERENCES orgmind.document(id) ON DELETE CASCADE,
  organization_id bigint NOT NULL REFERENCES orgmind.organization(id),
  department_id bigint REFERENCES orgmind.department(id),
  chunk_index integer NOT NULL,
  content text NOT NULL,
  page_number integer,
  embedding vector(768) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT document_chunk_order_unique UNIQUE (document_id, chunk_index)
);

CREATE TABLE IF NOT EXISTS orgmind.chat_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES orgmind.organization(id),
  department_id bigint REFERENCES orgmind.department(id),
  user_id bigint NOT NULL REFERENCES orgmind.app_user(id) ON DELETE CASCADE,
  query text NOT NULL,
  response text NOT NULL,
  agent_selected varchar(150) NOT NULL,
  uploaded_files text,
  category varchar(150) NOT NULL DEFAULT 'General',
  citations jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS department_organization_idx ON orgmind.department (organization_id);
CREATE INDEX IF NOT EXISTS role_organization_department_idx ON orgmind.role (organization_id, department_id);
CREATE INDEX IF NOT EXISTS app_user_scope_idx ON orgmind.app_user (organization_id, department_id);
CREATE INDEX IF NOT EXISTS refresh_token_user_idx ON orgmind.refresh_token (user_id, expires_at);
CREATE INDEX IF NOT EXISTS ingestion_request_scope_idx ON orgmind.ingestion_request (organization_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS document_scope_idx ON orgmind.document (organization_id, department_id, status);
CREATE INDEX IF NOT EXISTS document_chunk_scope_idx ON orgmind.document_chunk (organization_id, department_id, document_id);
CREATE INDEX IF NOT EXISTS chat_history_user_idx ON orgmind.chat_history (organization_id, user_id, created_at DESC);

